import { chromium } from 'playwright';
import { mkdir, writeFile, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
await mkdir('verification/screenshots', { recursive: true });
let executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE;
if (!executablePath && process.env.LOCALAPPDATA) { const cache = join(process.env.LOCALAPPDATA, 'ms-playwright'); const folders = await readdir(cache).catch(() => []); for (const folder of folders.filter(name => /^chromium-[0-9]+$/.test(name)).sort().reverse()) { const candidate = join(cache, folder, 'chrome-win64', 'chrome.exe'); if (existsSync(candidate)) { executablePath = candidate; break; } } }
const browser = await chromium.launch({ executablePath, headless: true, args: ['--use-angle=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
const errors = [], checks = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const check = (name, passed, detail = '') => { checks.push({ name, passed, detail }); if (!passed) throw new Error(name + ': ' + detail); };
try {
  await page.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1500);
  check('main menu is playable', await page.getByRole('button', { name: /ENTER THE ARENA/ }).isVisible());
  await page.screenshot({ path: 'verification/screenshots/menu.png' });
  await page.getByRole('button', { name: /ENTER THE ARENA/ }).click();
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'verification/screenshots/loadout.png' });
  check('six selectable fighters', await page.locator('.champion-roster button').count() === 6);
  check('three selectable arenas', await page.locator('.arena-option').count() === 3);
  await page.getByRole('button', { name: 'BEGIN DUEL', exact: true }).click();
  await page.waitForFunction(() => !!window.__veilstrike && !!window.__veilstrike.renderer.fighters[0].model && !!window.__veilstrike.renderer.fighters[1].model, { timeout: 25000 });
  await page.waitForSelector('.duel-loading', { state: 'detached', timeout: 25000 });
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'verification/screenshots/arena.png' });
  await page.getByRole('button', { name: /ESC.*MENU/ }).click();
  const frozen = await page.evaluate(() => window.__veilstrike.getSnapshot().time);
  await page.waitForTimeout(350);
  check('offline pause freezes combat', (await page.evaluate(() => window.__veilstrike.getSnapshot().time)) === frozen);
  await page.getByRole('button', { name: 'RETURN TO FIGHT', exact: true }).click();
  await page.keyboard.down('KeyW'); await page.waitForTimeout(350); await page.keyboard.up('KeyW');
  const before = await page.evaluate(() => window.__veilstrike.getSnapshot().fighters[0]);
  await page.keyboard.press('KeyJ'); await page.waitForTimeout(100);
  const attack = await page.evaluate(() => window.__veilstrike.getSnapshot().fighters[0]);
  check('keyboard attack is read by 3D combat', attack.stamina < before.stamina || !!attack.attack);
  await page.waitForTimeout(650);
  await page.keyboard.press('Space'); await page.waitForTimeout(100);
  const dodge = await page.evaluate(() => window.__veilstrike.getSnapshot().fighters[0]);
  check('dodge input changes combat state', dodge.state === 'dodge' || dodge.stamina < attack.stamina);
  await page.waitForTimeout(300);
  await page.keyboard.press('Tab');
  check('target lock can be toggled', !(await page.evaluate(() => window.__veilstrike.renderer.locked)));
  await page.getByRole('button', { name: /ESC.*MENU/ }).click();
  await page.getByRole('button', { name: 'LEAVE ARENA', exact: true }).click();
  await page.waitForTimeout(350);
  await page.getByRole('button', { name: /DROWNED GROVE/ }).click();
  await page.getByRole('button', { name: /NYX.*SOULBLADE/ }).click();
  await page.waitForTimeout(1000);
  await page.screenshot({ path: 'verification/screenshots/grove-loadout.png' });
  await page.getByRole('button', { name: 'BEGIN DUEL', exact: true }).click();
  await page.waitForSelector('.duel-loading', { state: 'detached', timeout: 25000 });
  await page.waitForTimeout(700);
  await page.screenshot({ path: 'verification/screenshots/grove.png' });
  await page.getByRole('button', { name: /ESC.*MENU/ }).click();
  await page.getByRole('button', { name: 'LEAVE ARENA', exact: true }).click();
  await page.getByRole('button', { name: /CINDER FORGE/ }).click();
  await page.getByRole('button', { name: /BRAKK.*WAR AXE/ }).click();
  await page.waitForTimeout(1000);
  await page.getByRole('button', { name: 'BEGIN DUEL', exact: true }).click();
  await page.waitForSelector('.duel-loading', { state: 'detached', timeout: 25000 });
  await page.waitForTimeout(700);
  await page.screenshot({ path: 'verification/screenshots/forge.png' });
  check('browser has no application errors', errors.length === 0, errors.join('\n'));
  const mobile = await context.newPage(); await mobile.setViewportSize({ width: 390, height: 844 });
  await mobile.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' });
  await mobile.getByRole('button', { name: /ENTER THE ARENA/ }).click();
  await mobile.waitForTimeout(700);
  check('mobile menu has no horizontal overflow', await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mobile.screenshot({ path: 'verification/screenshots/mobile-loadout.png', fullPage: true });
} catch (error) { checks.push({ name: 'verification failed', passed: false, detail: error.message }); process.exitCode = 1; }
finally { await writeFile('verification/browser-check.json', JSON.stringify({ checks, errors }, null, 2)); await context.close(); await browser.close(); }
console.log(JSON.stringify({ checks, errors }, null, 2));
